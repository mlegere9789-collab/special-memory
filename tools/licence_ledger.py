#!/usr/bin/env python3
"""Licence ledger (gate G4, supply chain).

Reads `cargo metadata --format-version 1 --locked` and writes docs/licences.md: every
third-party package in the resolved dependency graph with its name, exact version,
licence expression and source. Workspace members are the project's own code and are not listed.

    python3 tools/licence_ledger.py           write docs/licences.md
    python3 tools/licence_ledger.py --check   exit 1 if the committed file is out of date

Standard library only. The output is deterministic: rows are sorted by name then version.
"""
import difflib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "licences.md")
CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"
SPARSE_CRATES_IO = "sparse+https://index.crates.io/"


def metadata():
    res = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
    )
    if res.returncode != 0:
        sys.stderr.write(res.stderr)
        sys.exit(2)
    return json.loads(res.stdout)


def source_label(src):
    if src in (CRATES_IO, SPARSE_CRATES_IO):
        return "crates.io"
    return src


def cell(text):
    return text.replace("|", "\\|")


def render(meta):
    members = set(meta["workspace_members"])
    rows = []
    for p in meta["packages"]:
        if p["id"] in members:
            continue
        lic = p.get("license")
        if not lic:
            lic = "(file: %s)" % p["license_file"] if p.get("license_file") else "UNSPECIFIED"
        rows.append((p["name"], p["version"], lic, source_label(p.get("source") or "path")))
    rows.sort()
    lines = [
        "# Third-party licence ledger",
        "",
        "Generated by `python3 tools/licence_ledger.py` from `cargo metadata --locked`; do not edit by hand.",
        "CI runs `python3 tools/licence_ledger.py --check`. Licence policy is enforced by `deny.toml` (ADR 0005).",
        "",
        "%d third-party packages." % len(rows),
        "",
        "| Package | Version | Licence expression | Source |",
        "|---|---|---|---|",
    ]
    for name, ver, lic, src in rows:
        lines.append("| %s | %s | %s | %s |" % (cell(name), cell(ver), cell(lic), cell(src)))
    return "\n".join(lines) + "\n"


def main(argv):
    check = "--check" in argv
    text = render(metadata())
    if check:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            print("licence_ledger: docs/licences.md is missing; run python3 tools/licence_ledger.py")
            return 1
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(
                current.splitlines(True), text.splitlines(True), "docs/licences.md (committed)", "generated"))
            print("licence_ledger: docs/licences.md is out of date; run python3 tools/licence_ledger.py")
            return 1
        print("licence_ledger: docs/licences.md is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("licence_ledger: wrote docs/licences.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
